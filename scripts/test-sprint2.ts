import { newGame } from '../src/engine/newGame'
import { toCivil } from '../src/engine/core/calendar'
import { renewPuc, fitGps, retestFitness, dailyMaintenancePass } from '../src/engine/sim/maintenance'
import { dailyCheckpostPass } from '../src/engine/sim/checkpost'
import { appointDocsManager, hire, refreshHiringPool } from '../src/engine/sim/staffing'
import { buyUsed, refreshMarkets } from '../src/engine/sim/fleet'
import { BAL } from '../src/engine/data/balance'
import type { GameState, Bus } from '../src/engine/types'

function assert(cond: boolean, msg: string) {
  if (!cond) {
    console.error('FAIL:', msg)
    process.exit(1)
  }
  console.log('PASS:', msg)
}

function setupGameWithBus(seed: number): { s: GameState; bus: Bus } {
  const s = newGame('Test Fleet', 'malik', 'maa-blr', seed)
  refreshMarkets(s)
  refreshHiringPool(s)
  const l = s.usedMarket[0]
  if (!l) throw new Error('No listing in usedMarket')
  buyUsed(s, l.id, { loanProductId: 'shriram', months: 36 })
  const bus = Object.values(s.buses)[0]
  if (!bus) throw new Error('Failed to acquire bus')
  return { s, bus }
}

function testSprint2() {
  console.log('--- Testing Sprint 2 Features ---')

  // 1. Bus detail PUC manual renewal
  const { s: s1, bus: bus1 } = setupGameWithBus(101)
  assert(!!bus1, 'Initial bus exists')
  bus1.pucExpiryDay = s1.day - 1
  const cashBeforePuc = s1.company.cash
  const pucErr = renewPuc(s1, bus1.id)
  assert(pucErr === null, 'renewPuc succeeds')
  assert(bus1.pucExpiryDay === s1.day + BAL.pucValidityDays, 'PUC expiry updated by 180 days')
  assert(s1.company.cash === cashBeforePuc - BAL.pucCost, 'Cash reduced by PUC cost')

  // 2. Auto-renew PUC
  const { s: s2, bus: bus2 } = setupGameWithBus(102)
  bus2.pucExpiryDay = s2.day + 5 // within lead days (15)
  bus2.insuranceExpiryDay = s2.day + 300 // ensure other docs not due
  bus2.fitnessExpiryDay = s2.day + 300
  bus2.roadTaxPayableDay = s2.day + 300
  const txnsBefore = s2.txns.length
  dailyMaintenancePass(s2)
  console.log('Txns in auto-renew:', s2.txns.slice(txnsBefore))
  assert(bus2.pucExpiryDay === s2.day + BAL.pucValidityDays, 'Auto-renew renewed PUC within lead days')
  const pucTxn = s2.txns.find((t) => t.head === 'puc')
  assert(!!pucTxn && pucTxn.amount === BAL.pucCost, 'PUC transaction recorded with correct cost')

  // 3. Document manager daily consolidated summary log
  const { s: s3, bus: bus3 } = setupGameWithBus(103)
  hire(s3, s3.hiringPool[0].id)
  const staffMember = Object.values(s3.staff)[0]
  staffMember.role = 'manager'
  assert(!!staffMember, 'Staff member exists for docs manager')
  const appointRes = appointDocsManager(s3, staffMember.id)
  assert(appointRes === null, 'appointDocsManager succeeds')
  bus3.pucExpiryDay = s3.day + 2
  bus3.insuranceExpiryDay = s3.day + 2
  dailyMaintenancePass(s3)
  const summaryLog = s3.inbox.find((m) => m.text.startsWith('Docs renewed:'))
  assert(!!summaryLog, 'Single consolidated daily log line generated by docs manager: ' + summaryLog?.text)

  // 4. Checkpost grounds bus with expired fitness
  const { s: s4, bus: bus4 } = setupGameWithBus(104)
  bus4.fitnessExpiryDay = s4.day - 10
  // Fake a completed trip today
  s4.trips['fake_trip'] = {
    id: 'fake_trip',
    scheduleId: 'sch1',
    routeId: 'maa-blr',
    busId: bus4.id,
    day: s4.day,
    depHour: 8,
    direction: 'AB',
    status: 'completed',
    revenue: 10000,
    sold: 30,
    seats: [],
  } as any
  // Force checkpost interception
  BAL.checkpostDailyChance = 1.0
  dailyCheckpostPass(s4)
  assert(bus4.status === 'grounded', 'Bus with expired fitness grounded by checkpost')
  assert(bus4.impoundUntilDay !== undefined && bus4.impoundUntilDay > s4.day, 'Bus impounded for days')
  const raidLog = s4.inbox.find((m) => m.text.includes('CHECKPOST RAID'))
  assert(!!raidLog, 'Checkpost raid alert logged')
  BAL.checkpostDailyChance = 0.08 // restore

  // 5. GPS fitted reduces delay & missing GPS expressway penalty
  const { s: s5, bus: bus5 } = setupGameWithBus(105)
  bus5.gpsDeviceFitted = false
  const fitErr = fitGps(s5, bus5.id)
  assert(fitErr === null, 'fitGps succeeds')
  assert(bus5.gpsDeviceFitted === true, 'GPS device fitted successfully')

  // 6. Fitness failed RTO rule (> 10y and < 40% mechanicals)
  const { s: s6, bus: bus6 } = setupGameWithBus(106)
  bus6.mfgYear = toCivil(s6.day).y - 12 // > 10 years old at the game date
  bus6.condition.brakes = 35 // < 40%
  const retestErr = retestFitness(s6, bus6.id)
  assert(retestErr !== null && retestErr.includes('still under 40%'), 'Retest fails when mechanical condition < 40%')
  bus6.condition.brakes = 80
  const passRetestErr = retestFitness(s6, bus6.id)
  assert(passRetestErr === null, 'Retest succeeds after repairs')
  assert(bus6.fitnessFailed === false, 'fitnessFailed reset to false after pass')

  console.log('--- ALL SPRINT 2 TESTS PASSED ---')
}

testSprint2()
